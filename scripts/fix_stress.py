ACUTE = '\u0301'
VOW = 'аеёиоуыэюяАЕЁИОУЫЭЮЯ'

LATC = {'á':'а','à':'а','é':'е','è':'е','í':'и','ì':'и','ó':'о','ò':'о','ú':'у','ù':'у','ý':'ы',
        'â':'а','ê':'е','î':'и','ô':'о','û':'у',
        'Á':'А','É':'Е','Ó':'О','Ú':'У','Ý':'Ы','À':'А','È':'Е','Ì':'И','Ò':'О','Ù':'У'}
LOOK = {'c':'с','e':'е','a':'а','o':'о','p':'р','x':'х','y':'у','k':'к','m':'м','t':'т','h':'н',
        'B':'В','C':'С','E':'Е','H':'Н','K':'К','M':'М','T':'Т','A':'А','P':'Р','X':'Х','N':'Н','O':'О'}

def clean_text(t):
    t = unicodedata.normalize('NFD', t)
    out = []
    i = 0
    while i < len(t):
        ch = t[i]
        has_acute = False
        j = i + 1
        while j < len(t) and unicodedata.combining(t[j]):
            if t[j] == ACUTE:
                has_acute = True
            j += 1
        base = ch
        if base in LATC:
            base = LATC[base]
        elif ord(base) < 128 and base.lower() in 'aeiouy' and j < len(t) and '\u0400' <= t[j] <= '\u04FF':
            # accented latin vowel glued to cyrillic context (e.g. 'u\u0301в')
            base = {c.lower(): c for c, v in LATC.items()}.get(base.lower(), base) if False else {'a':'а','e':'е','i':'и','o':'о','u':'у','y':'ы'}[base.lower()]
            if base.isupper is None: pass
            base = base.upper() if ch.isupper() else base
            has_acute = True
        if has_acute and base in VOW:
            out.append(base + ACUTE)
        else:
            out.append(base)
        i = j
    s = ''.join(out)
    def fixw(m):
        w = m.group(0)
        if not re.search(r'[Ѐ-ӿ]', w):
            return w
        return ''.join(LOOK.get(c, c) if (ord(c) < 128 and ('a' <= c.lower() <= 'z')) else c for c in w)
    return re.sub(r'\S+', fixw, s)

