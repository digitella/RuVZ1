def restress_word(core, forced=None, phrase_map=None, low=None):
    """core: clean word (no marks). Returns word with exactly one acute (or none)."""
    vp = [i for i, c in enumerate(core) if c in VOW]
    if len(vp) <= 1:
        return core
    lw = core.lower()
    if lw in SKIPW and forced is None:
        return core
    idx = forced
    if idx is None and phrase_map is not None:
        idx = phrase_map.get(lw)
    if idx is None:
        idx = DICT.get(lw, 'LAST')
    if idx in (None, 'LAST'):
        p = vp[-1]
    elif isinstance(idx, int) and idx < len(vp):
        p = idx if False else vp[idx]
    else:
        p = vp[-1]
    return core[:p+1] + ACUTE + core[p+1:]

def restress(t, phrase_id=None):
    pm = PHRASE.get(phrase_id) if phrase_id else None
    out = []
    for w in re.split(r'(\s+)', t):
        if not w or w.isspace():
            out.append(w); continue
        m = re.match(r'^([^\w\-]*)(.*?)([^\w\-]*)$', w, re.U)
        pre, base, post = m.groups()
        core = base.replace(ACUTE, '')
        if not core:
            out.append(w); continue
        forced = None
        if pm is not None:
            lw = core.lower()
            if lw in pm:
                forced = pm[lw]  # may be None meaning "leave unstressed"
                if forced is None and lw in pm:
                    out.append(pre + core + post); continue
        out.append(pre + restress_word(core, forced, pm) + post)
    return ''.join(out)

def process(t, phrase_id=None):
    return restress(clean_text(t), phrase_id)

