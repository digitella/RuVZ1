"""Normalize Russian stress marks in course.json:
- collapse double U+0301, drop marks on consonants
- convert Latin lookalikes (é, á, u+0301...) to Cyrillic with combining acute
- fix Latin homoglyphs inside Cyrillic words (uвeдoмление -> уведомление)
- apply curated word-stress dictionary; default = last vowel for multi-syllable words
"""
